const DICTIONARIES: Record<Lang, Partial<Record<Key, string>>> = { en, ml, kn, te, hi, ta };
/** Text for `key` in `lang`, falling back to English. */
export const translate = (lang: Lang, key: Key) => DICTIONARIES[lang][key] ?? en[key];
/** The visitor's language: a saved choice, else the browser language if offered, else English. */
export function initialLang(): Lang {
  const saved = (() => { try { return localStorage.getItem('ca-territory-lang'); } catch { return null; } })();
  const wanted = [saved, ...navigator.languages.map((code) => code.slice(0, 2))];
  return (wanted.find((code) => LANGUAGES.some((language) => language.code === code)) as Lang | undefined) ?? 'en';
}
